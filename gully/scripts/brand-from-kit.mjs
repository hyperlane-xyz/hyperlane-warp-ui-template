// Copies GullyChain brand kit v4 (gully-ops sites/_shared/brand/kit-v4, byte-exact copy of GULLY LABS GRAPHICS/Gully
// Chain/brand-kit-v4), the GN 2.0 favicons and the bridge OG card, plus the Gully Labs badge, into public/, byte for byte
// (never re-encode a kit file). Kit v4 has no wordmark file: the header and footer show the icon only.
//   node scripts/brand-from-kit.mjs [gully-ops checkout] [gullylabs-kit-dir]
import { copyFileSync, mkdirSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const ops = process.argv[2] || new URL('../../../gully-ops', import.meta.url).pathname.replace(/^\/([A-Z]:)/, '$1');
const labs = process.argv[3] || 'C:/Users/Admin/Desktop/GULLY LABS GRAPHICS/Gully Labs/brand-kit';
const shared = join(ops, 'sites/_shared');
const kit = join(shared, 'brand/kit-v4');
const pub = new URL('../public/', import.meta.url).pathname.replace(/^\/([A-Z]:)/, '$1');
const cp = (from, to) => { mkdirSync(join(pub, to, '..'), { recursive: true }); copyFileSync(from, join(pub, to)); };

for (const f of ['favicon.svg', 'favicon-16.png', 'favicon-32.png', 'apple-touch-icon.png', 'android-chrome-192.png', 'android-chrome-512.png']) {
  cp(join(shared, 'landing', f), f);
}
cp(join(shared, 'brand/og/testnet-bridge.gullychain.xyz.png'), 'og-image.png');
// Gully Chain Night (black) surfaces: header = kit icon (32 px), footer = icon + the dark kit badge (960x256 at 180x48)
cp(join(kit, 'logo/gc-icon.svg'), 'brand/logo/gc-icon.svg');
cp(join(kit, 'badges/badge-dark.png'), 'brand/badges/badge-dark.png');
// "Powered by Gully Core" (kit v4 badges/gully-core, owner-approved 2026-10-30): full badge (194x56) + compact mark (146x24),
// dark ground only; shown on mirror routes (tests/night.test.ts hashes every copy)
for (const f of ['gully-core-powered-by-dark.svg', 'gully-core-powered-by-dark.png', 'gully-core-powered-by-dark-2x.png', 'gully-core-powered-by-dark-3x.png',
  'gully-core-mark-dark.svg', 'gully-core-mark-dark.png', 'gully-core-mark-dark-2x.png', 'gully-core-mark-dark-3x.png']) {
  cp(join(kit, 'badges/gully-core', f), `brand/badges/${f}`);
}
for (const f of readdirSync(join(labs, 'badges')).filter((f) => f.startsWith('powered-by-gully-labs-dark'))) cp(join(labs, 'badges', f), `brand/badges/${f}`);

writeFileSync(join(pub, 'site.webmanifest'), JSON.stringify({
  name: 'Gully Bridge', short_name: 'Gully Bridge',
  icons: [
    { src: 'favicon.svg', sizes: 'any', type: 'image/svg+xml' },
    { src: 'android-chrome-192.png', sizes: '192x192', type: 'image/png' },
    { src: 'android-chrome-512.png', sizes: '512x512', type: 'image/png' },
  ],
  start_url: './', theme_color: '#0A0F0E', background_color: '#0A0F0E', display: 'standalone',
}, null, 2) + '\n');
writeFileSync(join(pub, 'robots.txt'), 'User-agent: *\nAllow: /\nSitemap: https://testnet-bridge.gullychain.xyz/sitemap.xml\n');
// sitemap.xml is generated by vite.config.ts at build time (with lastmod)
console.log('brand assets copied into', pub);
